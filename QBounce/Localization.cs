    internal static string Get(TextId key, DisplayLanguage language)
    {
        var text = Translations[key];
        return language switch { DisplayLanguage.SimplifiedChinese => text.Cn, DisplayLanguage.TraditionalChinese => text.Tw, _ => text.En };
    }
    internal static string Format(TextId key, DisplayLanguage language, params object[] args) =>
        string.Format(CultureInfo.InvariantCulture, Get(key, language), args);

    internal static string NormalizePreference(string? value) =>
        Preferences.FirstOrDefault(p => p.Equals(value?.Trim(), StringComparison.OrdinalIgnoreCase)) ?? "auto";

    internal static DisplayLanguage Resolve(string? preference, string? hostLanguage)
    {
        var selected = NormalizePreference(preference);
        var code = (selected == "auto" ? hostLanguage : selected)?.Trim().Replace('_', '-').ToLowerInvariant() ?? "en";
        if (code is "tw" or "zh-tw" or "zh-hk" or "zh-mo" || code.StartsWith("zh-hant", StringComparison.Ordinal)) return DisplayLanguage.TraditionalChinese;
        return code == "zh" || code.StartsWith("zh-", StringComparison.Ordinal) ? DisplayLanguage.SimplifiedChinese : DisplayLanguage.English;
    }
